#!/usr/bin/env python3
"""Generate CP1252 forward and reverse tables from pinned primary Microsoft data."""
import argparse,hashlib,json,pathlib
R=pathlib.Path(__file__).resolve().parents[1];ap=argparse.ArgumentParser();ap.add_argument('--check',action='store_true');a=ap.parse_args()
d=json.loads((R/'config/encoding-sources.json').read_text());source=d['windows_best_fit'];raw=(R/source['local_path']).read_bytes();assert hashlib.sha256(raw).hexdigest()==source['sha256']
lines=raw.decode('ascii').splitlines();start=next(i for i,line in enumerate(lines) if line.startswith('MBTABLE 256'));table={}
for line in lines[start+1:]:
 parts=line.split(';')[0].split()
 if not parts:continue
 if not parts[0].startswith('0x'):break
 table[int(parts[0],16)]=int(parts[1],16)
assert sorted(table)==list(range(256));values=[table[i] for i in range(256)]
text='/* Generated by scripts/gen-codepage-table.py from Microsoft WindowsBestFit.\n   Source SHA256 '+source['sha256']+' */\nstatic const uint16_t cp1252_to_unicode[256]={\n'
text+=''.join('    '+','.join('0x%04x'%v for v in values[i:i+8])+',\n' for i in range(0,256,8))+'};\n'
start=next(i for i,line in enumerate(lines) if line.startswith('WCTABLE '));size=int(lines[start].split()[1]);reverse={}
for line in lines[start+1:]:
 parts=line.split(';')[0].split()
 if not parts:continue
 if not parts[0].startswith('0x'):break
 ch,byte=map(lambda x:int(x,16),parts[:2]);assert ch not in reverse and ch<=65535 and byte<=255;reverse[ch]=byte
assert len(reverse)==size and all(reverse[wide]==byte for byte,wide in table.items())
text+='/* Exact and best-fit reverse mappings; absent code units use CPINFO default 0x3f. */\nstatic const struct { uint16_t unicode; uint8_t byte; } cp1252_from_unicode[]={\n'
text+=''.join('    {0x%04x,0x%02x},\n'%(ch,byte) for ch,byte in sorted(reverse.items()))+'};\n'
p=R/'port/core/cp1252_table.inc' 
if a.check:assert p.read_text()==text,'Run scripts/gen-codepage-table.py'
else:p.write_text(text)
print('PASS: pinned Microsoft CP1252 MBTABLE and WCTABLE, 256 forward entries')
