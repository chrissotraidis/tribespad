#!/usr/bin/env python3
"""Generate the finite system export table from the declared runtime profile."""
import argparse,json,pathlib,re
R=pathlib.Path(__file__).resolve().parents[1]
def generate(j,bindings):
    exports=j['exports'];assert len({e['name'] for e in exports})==len(exports)==len({e['guest_va'] for e in exports})
    by_name={e['name']:e for e in exports};assert len({m['image'] for m in j['providers']})==len(j['providers'])
    text='/* Generated by scripts/gen-native-system-providers.py; edit the JSON profile. */\n'
    for e in exports:
        assert e['name'] in bindings and re.fullmatch(r'[A-Za-z0-9_]+',e['name'])
        assert 0xfffb0000<=e['guest_va']<0xfffc0000 and e['guest_va']%16==0
        text+='extern void tbimp_'+e['name']+'(void);\n'
    text+='typedef struct {uint32_t guest_va;void *host_function;} SystemRoute;\nstatic const SystemRoute system_routes[]={\n'
    text+=''.join('    {0x%xu,(void *)tbimp_%s},\n'%(e['guest_va'],e['name']) for e in exports)+'};\n'
    for i,m in enumerate(j['providers']):
        assert m['image'] in [0x60010000,0x60020000,0x20000000,0x20010000,0x20020000,0x20030000] and len(set(m['exports']))==len(m['exports'])
        assert m['initial_references'] in [0,1]
        assert m['path']=='C:\\Windows\\System32\\'+m['name']
        text+='static const TribesNativeExport system_exports_%d[]={\n'%i+''.join('    {"%s",0,0x%xu},\n'%(name,by_name[name]['guest_va']) for name in m['exports'])+'};\n'
    text+='typedef struct {uint32_t image;const char *path;const TribesNativeExport *exports;uint32_t count,initial_references;} SystemProvider;\nstatic const SystemProvider system_providers[]={\n'
    text+=''.join('    {0x%xu,%s,system_exports_%d,%d,%d},\n'%(m['image'],json.dumps(m['path']),i,len(m['exports']),m['initial_references']) for i,m in enumerate(j['providers']))+'};\n'
    return text

if __name__=="__main__":
    p=argparse.ArgumentParser();p.add_argument('--check',action='store_true');a=p.parse_args()
    j=json.loads((R/'config/runtime/native-providers.json').read_text());bindings=json.loads((R/'port/llasm-runtime/win32-bindings.json').read_text());text=generate(j,bindings)
    out=R/'port/core/native_system_providers.inc'
    if a.check:assert out.read_text()==text,'Regenerate native_system_providers.inc'
    else:out.write_text(text)
    print('PASS: finite native system-provider table matches profile' if a.check else 'Generated finite native system-provider table')
