#!/usr/bin/env python3
"""Generate finite Apple legacy GLSL templates from the pinned IFC22 resource.
No generic shader parser or replacement shader: only dialect changes in the
selected original sources; the original #inject payload remains a runtime hole.
"""
import argparse,hashlib,io,json,pathlib,re,zipfile
import pefile
ap=argparse.ArgumentParser();ap.add_argument('--mobile',action='store_true');args=ap.parse_args()
R=pathlib.Path(__file__).resolve().parents[1]
p=R/'ref/qol/IFC22.dll'
assert hashlib.sha256(p.read_bytes()).hexdigest()=='eaf5a42d301cc64a6e526aa49a82dbaefe655ed1ac0ba67939d0bab2fb6ab607'
pe=pefile.PE(str(p));archive=zipfile.ZipFile(io.BytesIO(pe.get_data(4677872,21234)))
rows=[]
for name in archive.namelist():
 if not name.endswith(('.vert','.frag')):continue
 original=archive.read(name).decode('utf-8');translated=original
 if args.mobile and name not in ('gui.vert','gui.frag'):continue
 translated=translated.replace('#version 150 compatibility','#version 120\n#extension GL_EXT_gpu_shader4 : require\n#extension GL_EXT_texture_array : require\n#extension GL_ARB_shader_texture_lod : require')
 if name.endswith('.frag'):
  for symbol in re.findall(r'^out vec4 (\w+);',translated,re.M):
   translated=re.sub(r'^out vec4 '+symbol+r';','',translated,flags=re.M)
   translated=re.sub(r'\b'+symbol+r'\b','gl_FragColor',translated)
 translated=re.sub(r'^(centroid |flat )?(in|out) ',lambda m:(m[1] or '')+('attribute ' if name.endswith('.vert') and m[2]=='in' else 'varying '),translated,flags=re.M)
 for before,after in [(r'\btextureLod\(splatMap','texture2DArrayLod(splatMap'),(r'\btexture\(splatMap','texture2DArray(splatMap'),(r'\btextureLod\(','texture2DLod('),(r'\btextureGrad\(','texture2DGradARB('),(r'\btextureSize\(','textureSize2D('),(r'\btexture\(','texture2D('),(r'\btexelFetch\(','texelFetch2DArray('),(r'\buint\b','unsigned int')]:translated=re.sub(before,after,translated)
 if args.mobile:
  translated=translated.replace('#extension GL_EXT_gpu_shader4 : require\n#extension GL_EXT_texture_array : require\n#extension GL_ARB_shader_texture_lod : require','#extension GL_EXT_shader_texture_lod : require')
  # This path is selected only without multisampling. The sole flat varying
  # is computed from a uniform, hence identical at every vertex.
  translated=translated.replace('centroid varying ','varying ').replace('flat varying ','varying ')
  translated=translated.replace('texCoord * texRes.xy','texCoord * vec2(texRes.xy)')
 assert original.count('#inject')<=1
 if '#inject' in original:
  pre,suffix=original.split('#inject');newpre,newsuffix=translated.split('#inject');hole=1
 else:pre,suffix,newpre,newsuffix,hole=original,'',translated,'',0
 rows.append(' {'+','.join([json.dumps(name),str(hole),json.dumps(pre),json.dumps(suffix),json.dumps(newpre),json.dumps(newsuffix)])+'},\n')
assert len(rows)==(2 if args.mobile else 12)
if args.mobile:
 (R/'port/core/mobile_shader_sources.inc').write_text('/* Pinned original GUI shaders; GLSL120 input for GL4ES, no MSAA.\n   Generated by generate-legacy-shaders.py --mobile. */\nstatic const LegacyShaderTemplate legacy_shader_templates[]={\n'+''.join(rows)+'};\n')
 raise SystemExit(0)
(R/'port/core/legacy_shader_sources.inc').write_text('/* Generated by scripts/generate-legacy-shaders.py from pinned IFC22.dll.\n   Native extensions: EXT_gpu_shader4, EXT_texture_array, ARB_shader_texture_lod.\n   EXT_gpu_shader4 uses "unsigned int" and supplies round/flat/integer varyings.\n   https://registry.khronos.org/OpenGL/extensions/EXT/EXT_gpu_shader4.txt */\nstatic const LegacyShaderTemplate legacy_shader_templates[]={\n'+''.join(rows)+'};\n')
