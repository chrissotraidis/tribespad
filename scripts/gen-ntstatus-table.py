#!/usr/bin/env python3
"""Generate the Wine 10.0 NTSTATUS map without Windows header dependencies."""
import argparse
import hashlib
import json
import pathlib
import re

R = pathlib.Path(__file__).resolve().parents[1]


def generate():
    manifest = json.loads((R / 'config/runtime/ntstatus-sources.json').read_text())
    assert manifest['revision'] == 'wine-10.0'
    sources = {}
    for row in manifest['files']:
        path = R / row['path']
        data = path.read_bytes()
        assert len(data) == row['bytes'] and hashlib.sha256(data).hexdigest() == row['sha256'], path
        sources[path.name] = data.decode()
    definitions = dict(re.findall(r'^#define\s+(\w+)\s+([^\n]+)', sources['winerror.h'] + '\n' + sources['ntstatus.h'], re.M))

    def number(name):
        value = definitions[name].split('/*')[0].strip()
        # Only three observed, integer-preserving forms. No Python eval or
        # silently accepted C expressions when the pinned source changes.
        value = re.sub(r'^_(?:HRESULT|NDIS_ERROR)_TYPEDEF_\((.*)\)$', r'\1', value)
        value = re.sub(r'^\(\(NTSTATUS\)\s*(.*?)\)$', r'\1', value)
        assert re.fullmatch(r'(?:0x[\da-fA-F]+|\d+)[uUlL]*', value), (name, value)
        return int(value.rstrip('uUlL'), 0)

    original = sources['error.h']
    map_start = original.index('static const DWORD error_map')
    table_start = original.index('static const struct')
    entries = re.findall(r'^\s+(\w+),\s*/\* ([\da-f]{8})(?: .*?)? \*/', original[map_start:table_start], re.M)
    ranges = [tuple(int(x, 0) for x in row) for row in re.findall(r'\{ (0x[\da-f]+), (0x[\da-f]+), (\d+) \}', original[table_start:])]
    assert len(entries) == 3129 and len(ranges) == 162
    expanded = []
    for start, end, offset in ranges:
        assert offset == len(expanded) and start <= end and (not expanded or start > expanded[-1])
        expanded.extend(range(start, end + 1))
    assert expanded == [int(address, 16) for _, address in entries]
    values = [number(name) for name, _ in entries]
    license_header = original[:original.index('/* conversion table')]
    text = license_header + '/* Generated by scripts/gen-ntstatus-table.py from wine-10.0.\n'
    text += '   Modified for TribesPad: numeric constants and fixed-width C types.\n'
    text += '   Source identities: config/runtime/ntstatus-sources.json. */\n'
    text += 'static const uint32_t ntstatus_errors[3129] = {\n'
    text += ''.join(' 0x%08xu, /* %s: %s */\n' % (value, address, name) for (name, address), value in zip(entries, values)) + '};\n'
    text += 'static const struct {uint32_t first,last,offset;} ntstatus_ranges[162] = {\n'
    text += ''.join(' {0x%08xu,0x%08xu,%du},\n' % row for row in ranges) + '};\n'
    return text


if __name__ == '__main__':
    parser = argparse.ArgumentParser()
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    output = R / 'port/core/ntstatus_table.inc'
    text = generate()
    if args.check:
        assert output.read_text() == text, 'Regenerate ntstatus_table.inc'
    else:
        output.write_text(text)
    print('PASS: 3129 pinned NTSTATUS entries in 162 validated ranges')
