#!/usr/bin/env python3
"""Generate the explicit CPU metadata compatibility constant from its profile."""
import argparse,hashlib,json,pathlib
R=pathlib.Path(__file__).resolve().parents[1];ap=argparse.ArgumentParser();ap.add_argument('--check',action='store_true');a=ap.parse_args()
p=json.loads((R/'config/runtime/cpu-metadata.json').read_text());reference=R/p['reference_path'];assert hashlib.sha256(reference.read_bytes()).hexdigest()==p['reference_sha256']
assert p['missing_frequency_mhz']==2400 and b'cpuspeed = 2400000000U;' in reference.read_bytes()
assert p['native_frequency_selector']=='hw.cpufrequency'
text='''/* Generated by scripts/gen-cpu-metadata.py. See config/runtime/cpu-metadata.json.
 * Explicit libuv Apple compatibility fallback; not measured physical MHz. */
#ifndef TRIBESPAD_CPU_METADATA_PROFILE_H
#define TRIBESPAD_CPU_METADATA_PROFILE_H
#define TRIBES_CPU_COMPATIBILITY_MHZ %du
#endif
'''%p['missing_frequency_mhz']
output=R/'port/core/cpu_metadata_profile.h'
if a.check:assert output.read_text()==text,'CPU metadata profile header is stale'
else:output.write_text(text)
print('CPU metadata compatibility profile verified' if a.check else 'Generated CPU metadata compatibility profile')
